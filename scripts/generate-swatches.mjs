/**
 * Extracts swatch data from TAPIS-GLOBAL-ASSETS/index.html → lib/swatches.ts
 * Run: node scripts/generate-swatches.mjs
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const htmlPath = path.resolve(__dirname, '../../TAPIS-GLOBAL-ASSETS/index.html')
const outPath = path.resolve(__dirname, '../lib/swatches.ts')

const html = fs.readFileSync(htmlPath, 'utf8')

const categories = []
const catRe =
  /sp-mat-title">([^<]+)<\/div>\s*<span class="sp-mat-tag">([^<]+)<\/span>/g
let m
while ((m = catRe.exec(html)) !== null) {
  const title = m[1].trim()
  const tagRaw = m[2].replace(/&middot;/g, '·').trim()
  const prefixMatch = tagRaw.match(/^([A-Z]+)/)
  categories.push({
    title,
    tag: tagRaw,
    prefix: prefixMatch ? prefixMatch[1] : '',
  })
}

const swatchRe =
  /<div class="sp-swatch"><img class="sp-swatch-img" src="([^"]+)" alt="([^"]*)"[^>]*><div class="sp-swatch-name">([^<]+)<\/div><div class="sp-swatch-code">([^<]+)<\/div><\/div>/g

const swatches = []
while ((m = swatchRe.exec(html)) !== null) {
  const [, image, alt, name, code] = m
  const prefix = code.replace(/\d+$/, '')
  swatches.push({ code, name: name || alt, image, prefix })
}

const catDefs = [
  { id: 'bsl', slug: 'botanical-silk-light', title: 'Botanical Silk Light', prefix: 'BSL', tag: 'BSL · 118 Shades', claimed: 118 },
  { id: 'bsh', slug: 'botanical-silk-heavy', title: 'Botanical Silk Heavy', prefix: 'BSH', tag: 'BSH · 90 Shades', claimed: 90 },
  { id: 'cpp', slug: 'cotton-pom-pom', title: 'Cotton Pom Pom', prefix: 'CPP', tag: 'CPP · 72 Shades', claimed: 72 },
  { id: 'wt', slug: 'wool-twist', title: 'Wool Twist', prefix: 'WT', tag: 'WT · 84 Shades', claimed: 84 },
  { id: 'vl', slug: 'viscose-lustre', title: 'Viscose Lustre', prefix: 'VL', tag: 'VL · 60 Shades', claimed: 60 },
  { id: 'jn', slug: 'jute-natural', title: 'Jute Natural', prefix: 'JN', tag: 'JN · 36 Shades', claimed: 36 },
]

for (const cat of catDefs) {
  cat.count = swatches.filter((s) => s.prefix === cat.prefix).length
}

const heroSlides = [
  { id: 0, src: 'https://images.unsplash.com/photo-1600566752355-35792bedcfea?w=1600&q=85', alt: 'Premium carpet texture' },
  { id: 1, src: 'https://images.unsplash.com/photo-1572123979839-3749e9973aba?w=1600&q=85', alt: 'Luxury rug detail' },
  { id: 2, src: 'https://images.unsplash.com/photo-1564444247765-a377a8bfd0b8?w=1600&q=85', alt: 'Handcrafted carpet' },
  { id: 3, src: 'https://images.unsplash.com/photo-1616980540826-5542d5aad277?w=1600&q=85', alt: 'Interior carpet installation' },
]

const lines = []
lines.push(`// AUTO-GENERATED by scripts/generate-swatches.mjs — do not edit manually`)
lines.push(`// Source: TAPIS-GLOBAL-ASSETS/index.html (${swatches.length} swatches)`)
lines.push(``)
lines.push(`export type SwatchCategoryId = 'bsl' | 'bsh' | 'cpp' | 'wt' | 'vl' | 'jn'`)
lines.push(`export type SwatchFilterId = SwatchCategoryId | 'all'`)
lines.push(``)
lines.push(`export interface SwatchCategory {`)
lines.push(`  id: SwatchCategoryId`)
lines.push(`  slug: string`)
lines.push(`  title: string`)
lines.push(`  tag: string`)
lines.push(`  prefix: string`)
lines.push(`  claimedShades: number`)
lines.push(`  swatchCount: number`)
lines.push(`}`)
lines.push(``)
lines.push(`export interface Swatch {`)
lines.push(`  code: string`)
lines.push(`  name: string`)
lines.push(`  image: string`)
lines.push(`  categoryId: SwatchCategoryId`)
lines.push(`  imageKey: string`)
lines.push(`}`)
lines.push(``)
lines.push(`export interface SampleHeroSlide {`)
lines.push(`  id: number`)
lines.push(`  src: string`)
lines.push(`  alt: string`)
lines.push(`}`)
lines.push(``)
lines.push(`export const SAMPLE_HERO_SLIDES: SampleHeroSlide[] = ${JSON.stringify(heroSlides, null, 2)}`)
lines.push(``)
lines.push(`export const SWATCH_CATEGORIES: SwatchCategory[] = ${JSON.stringify(
  catDefs.map((c) => ({
    id: c.id,
    slug: c.slug,
    title: c.title,
    tag: c.tag,
    prefix: c.prefix,
    claimedShades: c.claimed,
    swatchCount: c.count,
  })),
  null,
  2,
)}`)
lines.push(``)
lines.push(`export const SWATCHES: Swatch[] = [`)

for (const s of swatches) {
  const cat = catDefs.find((c) => c.prefix === s.prefix)
  if (!cat) continue
  const imageKey = s.image.match(/\/([^/]+\.jpg)$/)?.[1]?.replace('.jpg', '') ?? s.code.toLowerCase()
  lines.push(
    `  { code: ${JSON.stringify(s.code)}, name: ${JSON.stringify(s.name)}, image: ${JSON.stringify(s.image)}, categoryId: ${JSON.stringify(cat.id)}, imageKey: ${JSON.stringify(imageKey)} },`,
  )
}

lines.push(`]`)
lines.push(``)
lines.push(`export const SAMPLE_STATS = {`)
lines.push(`  totalSwatches: SWATCHES.length,`)
lines.push(`  totalCategories: SWATCH_CATEGORIES.length,`)
lines.push(`  headline: '430+ Pom Pom Swatches',`)
lines.push(`} as const`)
lines.push(``)
lines.push(`const CATEGORY_MAP = Object.fromEntries(`)
lines.push(`  SWATCH_CATEGORIES.map((c) => [c.id, c]),`)
lines.push(`) as Record<SwatchCategoryId, SwatchCategory>`)
lines.push(``)
lines.push(`export function getCategory(id: SwatchCategoryId): SwatchCategory {`)
lines.push(`  return CATEGORY_MAP[id]`)
lines.push(`}`)
lines.push(``)
lines.push(`export function filterSwatches(filter: SwatchFilterId): Swatch[] {`)
lines.push(`  if (filter === 'all') return SWATCHES`)
lines.push(`  return SWATCHES.filter((s) => s.categoryId === filter)`)
lines.push(`}`)
lines.push(``)
lines.push(`export function swatchesForCategory(id: SwatchCategoryId): Swatch[] {`)
lines.push(`  return SWATCHES.filter((s) => s.categoryId === id)`)
lines.push(`}`)
lines.push(``)
lines.push(`export function categoriesToShow(filter: SwatchFilterId): SwatchCategory[] {`)
lines.push(`  if (filter === 'all') return SWATCH_CATEGORIES`)
lines.push(`  return SWATCH_CATEGORIES.filter((c) => c.id === filter)`)
lines.push(`}`)

fs.writeFileSync(outPath, lines.join('\n'))
console.log(`Wrote ${outPath} (${swatches.length} swatches, ${catDefs.length} categories)`)
